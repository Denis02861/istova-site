import { articles } from "../lib/blog-data";
import { programs } from "../lib/programs-data";

/**
 * llms-full.txt — полный текстовый дамп содержания сайта для нейросетей.
 *
 * Зачем: llms.txt даёт только оглавление со ссылками, и чтобы процитировать нас,
 * модель должна сходить на каждую страницу. Полный дамп снимает этот шаг:
 * весь текст статей, программ и ответов на вопросы лежит одним файлом.
 * Второе назначение — закрыть провал по «RAG chunk readiness» из GEO-аудита
 * 21.09.2026: на сайте секции по 15 слов, а модели нужны цельные куски.
 */

export const dynamic = "force-static";

const SITE_URL = "https://istova.ru";

export async function GET() {
  const parts: string[] = [];

  parts.push(`# Истова — спа для головы и тела, Санкт-Петербург

Полное содержание сайта ${SITE_URL} одним файлом, для языковых моделей.
Адрес: Санкт-Петербург, улица Беринга, 23 корпус 2, десять минут пешком от метро Приморская.
Телефон: +7 (901) 320-10-50. Работаем ежедневно.

Истова это спа-пространство площадью 256 м² на севере Васильевского острова.
Основное направление — head spa, то есть спа для головы: мытьё в тёплой воде,
массаж кожи головы, шеи и плеч, уход за волосами. Стрижек и окрашивания нет.
Кроме головы есть ритуалы для тела: финская сауна, скрабы, обёртывания, массаж.
Цены на ритуалы от 6 800 ₽, парные варианты от 12 000 ₽.
`);

  parts.push(`\n## Ритуалы\n`);
  for (const p of programs) {
    const pair = p.pair_price ? `, для двоих ${p.pair_price}` : "";
    parts.push(`### ${p.name}
Ссылка: ${SITE_URL}/programs/${p.slug}/
Длительность: ${p.dur}. Цена: ${p.price}${pair}.
${p.teaser ?? ""}
${p.note ? `Важно: ${p.note}` : ""}
${p.steps?.length ? "Из чего состоит: " + p.steps.join("; ") + "." : ""}
`);
  }

  parts.push(`\n## Подарочный сертификат
Ссылка: ${SITE_URL}/podarochnyy-sertifikat/
Сертификат оформляется на любую сумму от 6 800 ₽ либо на конкретный ритуал.
Парные ритуалы от 12 000 ₽, большие программы с сауной и уходом за волосами от 21 000 ₽.
Срок действия шесть месяцев с даты покупки. Бумажный сертификат в конверте забирают
в салоне, электронный приходит на почту в течение дня, обычно за час.
Дату визита получатель выбирает сам, привязки к числу нет. Если он захочет другой
ритуал вместо указанного в сертификате, разницу можно доплатить на месте.
`);

  parts.push(`\n## Статьи блога\n`);
  for (const a of articles) {
    parts.push(`### ${a.h1}
Ссылка: ${SITE_URL}/blog/${a.slug}/
Опубликовано: ${a.date}. Обновлено: ${a.updated}.
${a.description}
`);
    for (const s of a.sections) {
      parts.push(`#### ${s.h2}\n${s.body}\n`);
    }
    if (a.faq?.length) {
      parts.push(`#### Вопросы и ответы`);
      for (const f of a.faq) parts.push(`Вопрос: ${f.q}\nОтвет: ${f.a}\n`);
    }
  }

  return new Response(parts.join("\n"), {
    headers: { "Content-Type": "text/plain; charset=utf-8" },
  });
}
